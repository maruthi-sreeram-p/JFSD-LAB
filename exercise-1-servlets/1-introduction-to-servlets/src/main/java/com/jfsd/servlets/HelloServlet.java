package com.jfsd.servlets;

import jakarta.servlet.ServletConfig;
import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;
import java.io.PrintWriter;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * First servlet. The three life cycle methods (init, service/doGet, destroy)
 * write to the server log so you can see when the container calls them.
 */
@WebServlet("/hello")
public class HelloServlet extends HttpServlet {

    private final AtomicInteger hits = new AtomicInteger();

    @Override
    public void init(ServletConfig config) throws ServletException {
        super.init(config);
        log("init() called - servlet object created, runs only once");
    }

    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        int count = hits.incrementAndGet();
        log("doGet() called - request number " + count);

        String name = request.getParameter("name");
        if (name == null || name.isBlank()) {
            name = "World";
        }

        response.setContentType("text/html;charset=UTF-8");
        PrintWriter out = response.getWriter();
        out.println("<!DOCTYPE html>");
        out.println("<html><head><title>Hello Servlet</title>");
        out.println("<link rel=\"stylesheet\" href=\"style.css\"></head><body>");
        out.println("<h1>Hello, " + escape(name) + "!</h1>");
        out.println("<p>This page was generated by <code>HelloServlet</code>.</p>");
        out.println("<p>Requests served since the servlet was loaded: <b>" + count + "</b></p>");
        out.println("<p class=\"muted\">Try <a href=\"hello?name=Abhiram\">hello?name=Abhiram</a></p>");
        out.println("<p><a href=\"index.html\">Back</a></p>");
        out.println("</body></html>");
    }

    @Override
    public void destroy() {
        log("destroy() called - servlet is being removed by the container");
    }

    private static String escape(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }
}
